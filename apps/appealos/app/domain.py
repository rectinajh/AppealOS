def canonicalize(value: Any) -> str:
    """RFC 8785-style canonical JSON compatible with apps/mockdrop/src/canonical.js."""
    if value is None or not isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=True, separators=(",", ":"))

    if isinstance(value, list):
        return "[" + ",".join(canonicalize(item) for item in value) + "]"

    entries = sorted(
        (key, item)
        for key, item in value.items()
        if item is not None
    )
    return (
        "{"
        + ",".join(
            f"{json.dumps(key, ensure_ascii=True)}:{canonicalize(item)}"
            for key, item in entries
        )
        + "}"
    )


def sha256_canonical(value: Any) -> str:
    return hashlib.sha256(canonicalize(value).encode("utf-8")).hexdigest()


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def parse_datetime(value: str) -> _dt.datetime:
    """Parse an ISO timestamp as an aware datetime for authorization checks."""
    parsed = _dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=_dt.timezone.utc)
    return parsed


